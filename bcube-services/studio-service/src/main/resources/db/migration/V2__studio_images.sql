-- Studio images move out of the studios row (a Base64 JSON gallery plus a large object, ~20 MB per
-- studio) into one row per image with two pre-scaled JPEGs: a small thumbnail for lists and a
-- display-sized image for detail views. The legacy columns stay for now so the data can be
-- migrated at startup (LegacyImageMigration) and rolled back if needed.
CREATE TABLE public.studio_images (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studio_id bigint NOT NULL REFERENCES public.studios(id) ON DELETE CASCADE,
    position integer NOT NULL,
    content_type character varying(50) NOT NULL,
    full_data bytea NOT NULL,
    thumb_data bytea NOT NULL,
    full_sha256 character varying(64) NOT NULL,
    thumb_sha256 character varying(64) NOT NULL,
    etag character varying(64) NOT NULL,
    CONSTRAINT uq_studio_images_position UNIQUE (studio_id, position)
);
